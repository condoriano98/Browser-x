"""Merges the layered GN args files in configs/ into one args.gn.

Layers (later wins): configs/common, configs/<platform>, configs/dev (dev
builds only). Only simple `name = value` lines are supported, which is all
our configs use; comments and blank lines are ignored.
"""

from __future__ import annotations

import re
from pathlib import Path

_LINE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.+?)\s*$")

# Args that must never be set to "true" in any Browser-x config: they would
# ship a test-only build, embed Google service keys, or need licensing that
# has not been decided (decision D9).
FORBIDDEN_TRUE = (
    "is_asan",
    "use_official_google_api_keys",
    "enable_widevine",
    "proprietary_codecs",
)


class GnArgsError(ValueError):
    pass


def parse_args_file(path: Path) -> dict[str, str]:
    result: dict[str, str] = {}
    for lineno, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        m = _LINE.match(line)
        if not m:
            raise GnArgsError(f"{path}:{lineno}: unsupported line {raw!r}")
        result[m.group(1)] = m.group(2)
    return result


def merge_layers(layers: list[Path]) -> dict[str, str]:
    merged: dict[str, str] = {}
    for layer in layers:
        if layer.is_file():
            merged.update(parse_args_file(layer))
    for name in FORBIDDEN_TRUE:
        if merged.get(name) == "true":
            raise GnArgsError(f"GN arg {name} = {merged[name]} is not allowed in Browser-x builds")
    return merged


def layers_for(repo: Path, platform: str, dev: bool) -> list[Path]:
    layers = [repo / "configs" / "common" / "args.gn", repo / "configs" / platform / "args.gn"]
    if dev:
        layers.append(repo / "configs" / "dev" / "args.gn")
    return layers


def render(args: dict[str, str], header: str) -> str:
    lines = [f"# {header}", "# Generated by `bx build`. Do not edit; change configs/*/args.gn."]
    lines += [f"{k} = {v}" for k, v in sorted(args.items())]
    return "\n".join(lines) + "\n"
